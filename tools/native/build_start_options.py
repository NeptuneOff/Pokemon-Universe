"""Generate the full opening partner pool from pinned evolution/Mega data.

Development only. Run read_showdown.mjs on the pinned pokedex.ts.gz first.
No national species number is passed to the legacy engine.
"""
import argparse
import hashlib
import json
from pathlib import Path


def stable_key(root, final, mega):
    value = 2166136261
    for byte in (root + '/' + final + '/' + mega).encode('ascii'):
        value = ((value ^ byte) * 16777619) & 0xffffffff
    return value


def compile_partners(dex, catalog, classic):
    names = {v['name']: k for k, v in dex.items()}
    entries = {e['id']: e for e in catalog['entries']}
    excluded = {e['id'] for pool in classic.values() for e in pool} | {'pikachu', 'eevee'}
    choices = []
    for mega in catalog['entries']:
        if not mega['mega'] or not mega['requirements']['item']:
            continue
        for final in mega['requirements']['from']:
            chain, current = [final], final
            if dex[final].get('evos'):
                continue  # Must be a terminal evolution, not an intermediate form.
            while dex[current].get('prevo'):
                previous = names[dex[current]['prevo']]
                if dex[current]['name'] not in dex[previous].get('evos', []):
                    raise ValueError('Non-reciprocal evolution edge: ' + current)
                if previous in chain:
                    raise ValueError('Evolution cycle: ' + previous)
                chain.insert(0, previous)
                current = previous
            if len(chain) < 2 or excluded.intersection(chain):
                continue
            choices.append({'key': stable_key(chain[0], final, mega['id']),
                'evolution_chain': chain, 'name_fr': entries[chain[0]]['name_fr'],
                'mega_id': mega['id'], 'stone_id': mega['requirements']['item'],
                'required_gender': dex[final].get('gender')})
    choices.sort(key=lambda p: (p['evolution_chain'][0], p['mega_id']))
    keys = {p['key'] for p in choices}
    if 0 in keys or len(keys) != len(choices):
        raise ValueError('Partner save-key collision')
    if len({p['evolution_chain'][0] for p in choices}) < 6:
        raise ValueError('Insufficient independent lines for two players')
    return choices


def c_partners(choices):
    roots = list(dict.fromkeys(p['evolution_chain'][0] for p in choices))
    out = ['/* Generated by build_start_options.py from pinned Showdown MIT data. */',
        'enum { PARTNER_POOL_COUNT = %d, PARTNER_ROOT_COUNT = %d };' % (len(choices), len(roots)),
        'static const PartnerRecord partner_pool[PARTNER_POOL_COUNT] = {']
    for p in choices:
        out.append('    {UINT32_C(%d), %s, %s, %s, %s},' % (p['key'],
            json.dumps(p['evolution_chain'][0]), json.dumps(p['evolution_chain'][-1]),
            json.dumps(p['mega_id']), "'%s'" % (p['required_gender'] or '-')))
    out += ['};', 'static const PartnerGroup partner_groups[PARTNER_ROOT_COUNT] = {']
    for root in roots:
        indices = [i for i, p in enumerate(choices) if p['evolution_chain'][0] == root]
        assert indices == list(range(indices[0], indices[0] + len(indices)))
        out.append('    {%d, %d}, /* %s */' % (indices[0], len(indices), root))
    out += ['};', '']
    return '\n'.join(out)


def build(pokedex, config_path, catalog_path, c_path):
    config = json.loads(Path(config_path).read_text(encoding='utf-8'))
    catalog = json.loads(Path(catalog_path).read_text(encoding='utf-8'))
    dex = json.loads(Path(pokedex).read_text(encoding='utf-8'))
    choices = compile_partners(dex, catalog, config['classic_pools'])
    config['schema'] = 2
    config['id'] = 'universe-opening-options-002'
    config['partner_choices'] = choices
    config['partner_draw'] = {'offers_per_player': 3, 'distinct_families_across_duo': True,
        'families': len({p['evolution_chain'][0] for p in choices}), 'evolution_mega_paths': len(choices),
        'method': 'Uniform family draw without replacement, then uniform eligible Mega target within family.',
        'source_catalog_sha256': hashlib.sha256(Path(catalog_path).read_bytes()).hexdigest(),
        'source_pokedex_json_sha256': hashlib.sha256(Path(pokedex).read_bytes()).hexdigest()}
    Path(config_path).write_bytes((json.dumps(config, ensure_ascii=False, indent=2) + '\n').encode())
    Path(c_path).write_bytes(c_partners(choices).encode())
    return config['partner_draw']


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--pokedex', required=True, type=Path)
    p.add_argument('--config', type=Path, default=Path('content/native/start-options.fr.json'))
    p.add_argument('--catalog', type=Path, default=Path('content/native/expansion/catalog.json'))
    p.add_argument('--c-output', type=Path, default=Path('native/universe/generated/journey.inc'))
    a = p.parse_args()
    print(json.dumps(build(a.pokedex, a.config, a.catalog, a.c_output)))
