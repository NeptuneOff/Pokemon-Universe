"""Compile metadata for the future engine extension, not the shipped binary."""
import argparse
import csv
import gzip
import hashlib
import json
from pathlib import Path
import re

TYPES = ['Normal', 'Fighting', 'Flying', 'Poison', 'Ground', 'Rock', 'Bug',
         'Ghost', 'Steel', '???', 'Fire', 'Water', 'Grass', 'Electric',
         'Psychic', 'Ice', 'Dragon', 'Dark', 'Fairy']
STATS = ['hp', 'atk', 'def', 'spa', 'spd', 'spe']
EXCLUDED = {'Gmax', 'Primal', 'Ultra', 'Totem', 'Starter'}


def key(name):
    return re.sub('[^a-z0-9]', '', name.lower())


def compile_catalog(source, names, provenance):
    entries = {}
    for identifier, species in source.items():
        number = species.get('num')
        if type(number) is not int or number <= 0 or species.get('isNonstandard') == 'Custom':
            continue
        if not re.fullmatch('[a-z0-9]+', identifier) or number > 65535:
            raise ValueError('Invalid species identifier')
        forme = species.get('forme', '')
        if set(forme.split('-')) & EXCLUDED:
            continue
        stats = [species['baseStats'][s] for s in STATS]
        if any(type(s) is not int or not 1 <= s <= 65535 for s in stats):
            raise ValueError('Invalid base stats: ' + identifier)
        types = species['types']
        if not 1 <= len(types) <= 2 or any(t not in TYPES or t == '???' for t in types):
            raise ValueError('Invalid types: ' + identifier)
        if number not in names or not names[number].strip():
            raise ValueError('Missing French name: ' + str(number))
        mega = 'Mega' in forme.split('-')
        base = key(species.get('baseSpecies', species['name']))
        before = species.get('battleOnly', species.get('changesFrom', base))
        if isinstance(before, str):
            before = [before]
        eligible = [key(x) for x in before] if mega else []
        item, move = key(species.get('requiredItem', '')), key(species.get('requiredMove', ''))
        if mega and (not eligible or len(eligible) > 4 or not (item or move)):
            raise ValueError('Incomplete Mega requirements: ' + identifier)
        abilities = [key(species.get('abilities', {}).get(slot, '')) for slot in ('0', '1', 'H')]
        if not abilities[0]:
            raise ValueError('Missing primary ability: ' + identifier)
        entries[identifier] = {
            'id': identifier, 'national_dex': number, 'base_id': base,
            'name_fr': names[number], 'form': forme or None, 'mega': mega,
            'types': types, 'base_stats': dict(zip(STATS, stats)), 'abilities': abilities,
            'requirements': {'from': eligible, 'item': item or None, 'move': move or None} if mega else None,
            # #494 is Egg in Platinum, Victini in the national dex: never alias.
            'legacy_native_species_id': number if not species.get('baseSpecies') and number <= 493 else None,
        }
    bases = {}
    for e in entries.values():
        if e['base_id'] == e['id']:
            if e['national_dex'] in bases:
                raise ValueError('Duplicate national species')
            bases[e['national_dex']] = e['id']
        if e['base_id'] not in entries:
            raise ValueError('Missing base form: ' + e['id'])
        if e['mega']:
            for previous in e['requirements']['from']:
                if previous not in entries or entries[previous]['mega'] or entries[previous]['national_dex'] != e['national_dex']:
                    raise ValueError('Invalid Mega source form: ' + e['id'] + ' <- ' + previous)
    if not bases or sorted(bases) != list(range(1, max(bases) + 1)):
        raise ValueError('National species list has gaps')
    ordered = sorted(entries.values(), key=lambda e: e['id'])
    return {'schema': 1, 'status': 'engine-extension-not-linked', 'sources': provenance,
            'type_ids': dict(zip(TYPES, range(len(TYPES)))),
            'counts': {'national_species': len(bases), 'forms': len(ordered),
                       'mega_forms': sum(e['mega'] for e in ordered)}, 'entries': ordered}


def literal(value):
    return json.dumps(value or '', ensure_ascii=True)


def c_catalog(catalog):
    lines = ['/* Generated by build_expansion_catalog.py. Do not edit. */',
             '/* Data: Pokemon Showdown (MIT), see data/SHOWDOWN-LICENSE. */',
             'static const UnivSpecies catalog[] = {']
    for e in catalog['entries']:
        r = e['requirements'] or {'from': [], 'item': None, 'move': None}
        eligible = r['from'] + [''] * (4 - len(r['from']))
        type_ids = [TYPES.index(t) for t in e['types']]
        if len(type_ids) == 1:
            type_ids.append(type_ids[0])
        fields = [literal(e['id']), str(e['national_dex']), str(int(e['mega'])),
                  '{' + ','.join(str(e['base_stats'][s]) for s in STATS) + '}',
                  '{' + ','.join(map(str, type_ids)) + '}',
                  '{' + ','.join(map(literal, e['abilities'])) + '}',
                  '{' + ','.join(map(literal, eligible)) + '}', literal(r['item']), literal(r['move'])]
        lines.append('    {' + ', '.join(fields) + '},')
    return '\n'.join(lines + ['};', ''])


def build(pokedex, names_path, source_info, catalog_path, c_path):
    opener = gzip.open if str(names_path).endswith('.gz') else open
    with opener(names_path, 'rt', encoding='utf-8', newline='') as stream:
        names = {int(r['pokemon_species_id']): r['name'] for r in csv.DictReader(stream) if r['local_language_id'] == '5'}
    catalog = compile_catalog(json.loads(Path(pokedex).read_text(encoding='utf-8')), names, source_info)
    for path, data in ((catalog_path, json.dumps(catalog, ensure_ascii=False, separators=(',', ':')) + '\n'),
                       (c_path, c_catalog(catalog))):
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        Path(path).write_text(data, encoding='utf-8')
    return catalog['counts']


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--pokedex', type=Path, required=True)
    p.add_argument('--names', type=Path, required=True)
    p.add_argument('--provenance', type=Path, required=True)
    p.add_argument('--catalog', type=Path, required=True)
    p.add_argument('--c-output', type=Path, required=True)
    a = p.parse_args()
    print(json.dumps(build(a.pokedex, a.names, json.loads(a.provenance.read_text(encoding='utf-8')), a.catalog, a.c_output)))
